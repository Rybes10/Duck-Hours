function renderFileTabs() {
  persistWorkspace();
  fileTabs.querySelectorAll('.file-tab-item').forEach(item => item.remove());
  fileTabs.querySelectorAll(':scope > [role="tab"]').forEach(tab => tab.remove());
  fileTabs.querySelector('.file-tabs-empty')?.remove();
  fileTabs.dataset.empty = String(files.length === 0);
  editorEmptyState.hidden = files.length > 0;
  if (files.length === 0) {
    fileTabs.insertBefore(createElement('span', 'file-tabs-empty', 'No files open'), addFileButton);
  }
  const fixtureNames = new Set(testCases.flatMap(testCase => testCase.files.map(fixture => fixture.fileName).filter(Boolean)));
  const outputNames = new Set(testCases.flatMap(testCase => testCase.expectedFiles.map(file => String(file.name || '').trim().toLowerCase()).filter(Boolean)));
  files.forEach(file => {
    const item = createElement('div', 'file-tab-item');
    item.dataset.fileId = file.id;
    item.dataset.active = String(file.id === activeFileId);
    item.dataset.generated = String(Boolean(file.generated));
    item.dataset.hasFixture = String(fixtureNames.has(file.name));
    item.dataset.hasOutputCheck = String(outputNames.has(file.name.toLowerCase()));
    item.draggable = true;
    const tab = createElement('button', 'file-tab', file.name);
    tab.className = 'file-tab';
    tab.type = 'button';
    tab.setAttribute('role', 'tab');
    tab.setAttribute('aria-controls', 'editor');
    tab.setAttribute('aria-selected', String(file.id === activeFileId));
    tab.tabIndex = file.id === activeFileId ? 0 : -1;
    tab.title = file.generated ? `${file.name} — generated by the last run` : file.name;
    tab.addEventListener('click', event => {
      if (event.detail > 1) return;
      if (window.__duckHoursFileTabClickTimer) window.clearTimeout(window.__duckHoursFileTabClickTimer);
      window.__duckHoursFileTabClickTimer = window.setTimeout(() => {
        window.__duckHoursFileTabClickTimer = null;
        selectFile(file.id);
      }, 220);
    });
    if (!file.generated) tab.title += ' — double-click to rename';
    tab.addEventListener('dblclick', event => {
      if (file.generated) return;
      event.preventDefault();
      event.stopPropagation();
      if (window.__duckHoursFileTabClickTimer) {
        window.clearTimeout(window.__duckHoursFileTabClickTimer);
        window.__duckHoursFileTabClickTimer = null;
      }
      startFileRename(file, tab);
    });
    const deleteButton = createElement('button', 'delete-file', '×');
    deleteButton.type = 'button';
    deleteButton.disabled = false;
    deleteButton.title = `Close ${file.name}; reopen it from Files`;
    deleteButton.setAttribute('aria-label', `Close ${file.name} tab`);
    deleteButton.addEventListener('click', () => closeFile(file.id));
    item.append(tab, deleteButton);
    fileTabs.insertBefore(item, addFileButton);
  });
  renderWorkspaceFiles();
}

function renderWorkspaceFiles() {
  const list = document.querySelector('#workspace-files-list');
  if (!list) return;
  list.replaceChildren();
  const count = document.querySelector('#workspace-files-count');
  if (count) {
    const fileCount = allWorkspaceFiles().length;
    count.textContent = `${fileCount} file${fileCount === 1 ? '' : 's'}`;
    const tabCount = document.querySelector('#workspace-files-tab .sidebar-tab-count');
    if (tabCount) tabCount.textContent = String(fileCount);
  }
  for (const file of allWorkspaceFiles()) {
    const row = createElement('div', 'workspace-file-row');
    const details = createElement('div', 'workspace-file-details');
    const name = createElement('strong', '', file.name);
    name.title = 'Double-click to rename';
    name.addEventListener('dblclick', () => startFileRename(file, name));
    details.append(name);
    const tags = [];
    if (testCases.some(testCase => testCase.files.some(fixture => fixture.fileName === file.name))) tags.push('Input');
    if (testCases.some(testCase => testCase.expectedFiles.some(expected => expected.name === file.name))) tags.push('Expected output');
    if (file.generated) tags.push('Generated');
    details.append(createElement('span', 'workspace-file-properties', `${files.includes(file) ? 'Open in editor' : 'Closed'}${tags.length ? ` · ${tags.join(' · ')}` : ''}`));
    const open = createElement('button', 'workspace-file-open', 'Open');
    open.type = 'button';
    open.disabled = file.id === activeFileId;
    open.addEventListener('click', () => openWorkspaceFile(file.id));
    const remove = createElement('button', 'workspace-file-delete', 'Delete');
    remove.type = 'button';
    remove.setAttribute('aria-label', `Delete ${file.name} from workspace`);
    remove.addEventListener('click', () => {
      if (window.confirm(`Permanently delete "${file.name}" from this workspace?`)) removeWorkspaceFile(file.id);
    });
    row.append(details, open, remove);
    list.append(row);
  }
}

function startFileRename(file, label) {
  if (!file || file.generated || !label?.isConnected) return;
  const input = createElement('input', label.classList.contains('file-tab') ? 'file-tab-rename' : 'workspace-file-rename');
  input.value = file.name;
  input.setAttribute('aria-label', `Rename ${file.name}`);
  label.replaceWith(input);
  input.focus();
  input.select();
  let finished = false;
  const finish = commit => {
    if (finished) return;
    if (!commit) {
      finished = true;
      renderFileTabs();
      return;
    }
    const requestedName = input.value.trim();
    if (!/^[A-Za-z0-9_][A-Za-z0-9_.-]{0,99}$/.test(requestedName) || requestedName === '.' || requestedName === '..') {
      input.setAttribute('aria-invalid', 'true');
      input.title = 'Use a name with letters, numbers, dots, dashes, or underscores.';
      input.focus();
      input.select();
      return;
    }
    finished = true;
    applyFileRename(file, requestedName);
  };
  input.addEventListener('keydown', event => {
    if (event.key === 'Enter') {
      event.preventDefault();
      finish(true);
    }
    if (event.key === 'Escape') {
      event.preventDefault();
      finish(false);
    }
  });
  input.addEventListener('blur', () => finish(true));
}

function applyFileRename(file, requestedName) {
  const previousName = file.name;
  file.name = uniqueFileName(requestedName, file.id);
  const language = languageByExtension[file.name.split('.').pop().toLowerCase()];
  if (language) {
    file.language = language;
    monaco.editor.setModelLanguage(file.model, language);
    if (file.id === activeFileId && !file.generated) {
      currentLanguage = language;
      languageSelect.value = language;
    }
  }
  testCases.forEach(testCase => {
    testCase.files.forEach(fixture => {
      if (fixture.fileName === previousName) fixture.fileName = file.name;
    });
    testCase.expectedFiles.forEach(expected => {
      if (expected.name === previousName) expected.name = file.name;
    });
  });
  markTestCasesOutdated();
  renderFileTabs();
  renderTestCases();
  if (file.id === activeFileId && outputStatus?.textContent === 'Ready') {
    output.textContent = `Ready to run ${file.name}.`;
  }
}

function selectFile(fileId) {
  const file = files.find(item => item.id === fileId);
  if (!file || !codeEditor) return;
  activeFileId = fileId;
  codeEditor.setModel(file.model);
  codeEditor.updateOptions({readOnly: Boolean(file.generated)});
  languageSelect.disabled = Boolean(file.generated);
  if (!file.generated) {
    currentLanguage = file.language;
    languageSelect.value = currentLanguage;
  }
  renderFileTabs();
  updateFileControls();
  output.className = 'output-box';
  output.textContent = `Ready to run ${file.name}.`;
  outputStatus.textContent = 'Ready';
  persistWorkspace();
}

function openWorkspaceFile(fileId) {
  let file = files.find(item => item.id === fileId);
  if (!file) {
    const index = closedFiles.findIndex(item => item.id === fileId);
    if (index < 0) return;
    [file] = closedFiles.splice(index, 1);
    files.push(file);
  }
  selectFile(file.id);
  renderTestCases();
}

addFileButton.addEventListener('click', () => {
  if (!codeEditor || allWorkspaceFiles().length >= 20) return;
  const extension = extensionByLanguage[currentLanguage] || currentLanguage;
  const fileNumber = nextFileNumber++;
  const fileId = `file-${fileNumber}`;
  const fileName = `untitled-${fileNumber}.${extension}`;
  const model = monaco.editor.createModel('', currentLanguage);
  files.push({id: fileId, name: fileName, language: currentLanguage, model});
  selectFile(fileId);
  renderTestCases();
  updateFileControls();
});

function closeFile(fileId) {
  if (files.length === 0) return;
  const index = files.findIndex(file => file.id === fileId);
  if (index < 0) return;
  const [closedFile] = files.splice(index, 1);
  closedFiles.push(closedFile);
  if (activeFileId === fileId && files.length > 0) {
    const nextFile = files.find(file => !file.generated) || files[Math.min(index, files.length - 1)];
    activeFileId = nextFile.id;
    codeEditor.setModel(nextFile.model);
    codeEditor.updateOptions({readOnly: Boolean(nextFile.generated)});
    languageSelect.disabled = Boolean(nextFile.generated);
    if (!nextFile.generated) {
      currentLanguage = nextFile.language;
      languageSelect.value = currentLanguage;
    }
  } else if (activeFileId === fileId) {
    clearHints();
    activeFileId = null;
    lastRun = null;
    codeEditor.setModel(null);
    codeEditor.updateOptions({readOnly: false});
    languageSelect.disabled = false;
    output.className = 'output-box';
    output.textContent = 'Add a file or import one to run code.';
    outputStatus.textContent = 'No file open';
  }
  renderFileTabs();
  renderTestCases();
  updateFileControls();
}

function removeWorkspaceFile(fileId) {
  let collection = files;
  let index = collection.findIndex(file => file.id === fileId);
  if (index < 0) {
    collection = closedFiles;
    index = collection.findIndex(file => file.id === fileId);
  }
  if (index < 0) return;
  const [removed] = collection.splice(index, 1);
  if (activeFileId === fileId) {
    const next = files.find(file => !file.generated) || files[0];
    if (next) selectFile(next.id);
    else {
      clearHints();
      activeFileId = null;
      lastRun = null;
      codeEditor.setModel(null);
      output.textContent = 'Open or add a file to run code.';
      outputStatus.textContent = 'No file open';
    }
  }
  removed.model.dispose();
  testCases.forEach(testCase => {
    testCase.files = testCase.files.filter(fixture => fixture.fileName !== removed.name);
  });
  markTestCasesOutdated();
  renderFileTabs();
  renderTestCases();
  updateFileControls();
}

function updateFileControls() {
  const atLimit = allWorkspaceFiles().length >= 20;
  addFileButton.disabled = !codeEditor || atLimit;
  importButton.disabled = !codeEditor || atLimit;
  const activeFile = files.find(file => file.id === activeFileId);
  runButton.disabled = !codeEditor || !activeFile || activeFile.generated;
  addFileButton.title = atLimit ? 'A workspace can contain up to 20 files' : 'Add file';
}

function uniqueFileName(candidate, exceptFileId = null) {
  const cleaned = candidate.replace(/[^A-Za-z0-9_.-]/g, '_').replace(/^[^A-Za-z0-9_]+/, '') || 'imported.txt';
  const dot = cleaned.lastIndexOf('.');
  const stem = dot > 0 ? cleaned.slice(0, dot) : cleaned;
  const extension = dot > 0 ? cleaned.slice(dot) : '';
  let name = cleaned;
  let suffix = 2;
  while (allWorkspaceFiles().some(file => file.id !== exceptFileId && file.name === name)) {
    name = `${stem}-${suffix}${extension}`;
    suffix += 1;
  }
  return name;
}

async function importFiles(importedFiles) {
  if (!codeEditor) return;
  for (const importedFile of importedFiles) {
    if (allWorkspaceFiles().length >= 20) break;
    const name = uniqueFileName(importedFile.name);
    const extension = name.split('.').pop().toLowerCase();
    const language = languageByExtension[extension] || currentLanguage;
    const source = await importedFile.text();
    const model = monaco.editor.createModel(source, language);
    const id = `file-${nextFileNumber++}`;
    files.push({id, name, language, model});
    activeFileId = id;
    currentLanguage = language;
    codeEditor.setModel(model);
    languageSelect.value = language;
  }
  const activeModel = codeEditor.getModel();
  if (activeModel) monaco.editor.setModelMarkers(activeModel, 'office-hours-prep', []);
  renderFileTabs();
  renderTestCases();
  updateFileControls();
}

function showGeneratedFiles(generatedFiles) {
  const wasActiveGenerated = files.some(file => file.id === activeFileId && file.generated);
  if (wasActiveGenerated) {
    const nextFile = files.find(file => !file.generated);
    activeFileId = nextFile?.id ?? null;
    currentLanguage = nextFile?.language ?? currentLanguage;
    codeEditor.setModel(nextFile?.model ?? null);
    codeEditor.updateOptions({readOnly: false});
    languageSelect.disabled = false;
    if (nextFile) languageSelect.value = currentLanguage;
  }
  for (let index = files.length - 1; index >= 0; index -= 1) {
    if (!files[index].generated) continue;
    files[index].model.dispose();
    files.splice(index, 1);
  }
  for (let index = closedFiles.length - 1; index >= 0; index -= 1) {
    if (!closedFiles[index].generated) continue;
    closedFiles[index].model.dispose();
    closedFiles.splice(index, 1);
  }
  const availableSlots = Math.max(0, 20 - allWorkspaceFiles().length);
  (generatedFiles || []).slice(0, availableSlots).forEach(file => {
    if (!file?.name || allWorkspaceFiles().some(openFile => openFile.name === file.name)) return;
    const extension = file.name.split('.').pop().toLowerCase();
    const language = languageByExtension[extension] || currentLanguage;
    const model = monaco.editor.createModel(file.contents || '', language);
    files.push({id: `generated-${nextFileNumber++}`, name: file.name, language, model, generated: true});
  });
  renderFileTabs();
  updateFileControls();
}

fileTabs.addEventListener('dragstart', event => {
  const item = event.target.closest('.file-tab-item');
  if (!item) return;
  event.dataTransfer.effectAllowed = 'move';
  event.dataTransfer.setData('text/plain', item.dataset.fileId);
  item.classList.add('dragging');
});

fileTabs.addEventListener('dragover', event => {
  const target = event.target.closest('.file-tab-item');
  if (!target) return;
  event.preventDefault();
  fileTabs.querySelectorAll('.drop-target').forEach(item => item.classList.remove('drop-target'));
  target.classList.add('drop-target');
});

fileTabs.addEventListener('drop', event => {
  const target = event.target.closest('.file-tab-item');
  const sourceId = event.dataTransfer.getData('text/plain');
  if (!target || !sourceId || target.dataset.fileId === sourceId) return;
  event.preventDefault();
  const sourceIndex = files.findIndex(file => file.id === sourceId);
  const targetIndex = files.findIndex(file => file.id === target.dataset.fileId);
  if (sourceIndex < 0 || targetIndex < 0) return;
  const targetBounds = target.getBoundingClientRect();
  const insertIndex = targetIndex + (event.clientX > targetBounds.left + targetBounds.width / 2 ? 1 : 0);
  const [movedFile] = files.splice(sourceIndex, 1);
  files.splice(sourceIndex < insertIndex ? insertIndex - 1 : insertIndex, 0, movedFile);
  renderFileTabs();
  fileTabs.querySelector(`[data-file-id="${activeFileId}"]`)?.scrollIntoView({block: 'nearest', inline: 'nearest'});
});

fileTabs.addEventListener('dragend', () => {
  fileTabs.querySelectorAll('.dragging,.drop-target').forEach(item => item.classList.remove('dragging', 'drop-target'));
});

fileTabs.addEventListener('keydown', event => {
  if (!['ArrowLeft', 'ArrowRight'].includes(event.key)) return;
  const tabs = [...fileTabs.querySelectorAll('[role="tab"]')];
  const activeIndex = tabs.indexOf(document.activeElement);
  if (activeIndex < 0 || tabs.length < 2) return;
  event.preventDefault();
  const offset = event.key === 'ArrowRight' ? 1 : -1;
  const nextTab = tabs[(activeIndex + offset + tabs.length) % tabs.length];
  nextTab.focus();
  nextTab.click();
});

languageSelect.addEventListener('change', () => {
  currentLanguage = languageSelect.value;
  if (!codeEditor) return;
  const activeFile = files.find(file => file.id === activeFileId);
  if (!activeFile) return;
  if (activeFile) {
    const previousName = activeFile.name;
    activeFile.language = currentLanguage;
    activeFile.name = uniqueFileName(activeFile.name.replace(/\.[^.]+$/, `.${extensionByLanguage[currentLanguage] || currentLanguage}`), activeFile.id);
    testCases.forEach(testCase => {
      testCase.files.forEach(fixture => {
        if (fixture.fileName === previousName) fixture.fileName = activeFile.name;
      });
      testCase.expectedFiles.forEach(expected => {
        if (expected.name === previousName) expected.name = activeFile.name;
      });
    });
  }
  // Changing the language changes syntax highlighting and the file extension,
  // but it must never replace the user's open-file contents with an example.
  monaco.editor.setModelLanguage(codeEditor.getModel(), currentLanguage);
  lastRun = null;
  clearHints();
  monaco.editor.setModelMarkers(codeEditor.getModel(), 'office-hours-prep', []);
  renderFileTabs();
  output.className = 'output-box';
  output.textContent = `Ready to run ${languageSelect.options[languageSelect.selectedIndex].text}.`;
  outputStatus.textContent = 'Ready';
  renderTestCases();
  window.scheduleTestTargetValidation?.();
});
